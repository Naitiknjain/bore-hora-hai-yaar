export const CATEGORIES: GameCategory[] = ['Arcade', 'Puzzle', 'Classic', 'Skill']

export const GAME_BY_ID = Object.fromEntries(GAMES.map((g) => [g.id, g])) as Record<GameId, GameMeta>

export function getGame(id: string | undefined): GameMeta | undefined {
  return id ? GAME_BY_ID[id as GameId] : undefined
}

export function searchGames(query: string, category: GameCategory | 'All'): GameMeta[] {
  const q = query.trim().toLowerCase()
  return GAMES.filter((g) => {
    if (category !== 'All' && g.category !== category) return false
    if (!q) return true
    return g.name.toLowerCase().includes(q) || g.tags.some((t) => t.includes(q)) || g.tagline.toLowerCase().includes(q)
  })
}
